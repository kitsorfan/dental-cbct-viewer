let lang = 'en';

export function getLanguage() {
  return lang;
}

export function localeFor(id = lang) {
  return LANGUAGES.find((l) => l.id === id)?.locale ?? 'en-GB';
}

// ?lang= first, then the browser's preferred languages.
export function detectLanguage() {
  const param = new URLSearchParams(globalThis.location?.search ?? '').get('lang');
  if (param && STRINGS[param]) return param;
  const prefs = globalThis.navigator?.languages ?? [globalThis.navigator?.language ?? ''];
  for (const p of prefs) {
    const id = String(p).toLowerCase().slice(0, 2);
    if (STRINGS[id]) return id;
  }
  return 'en';
}

export function t(key: string, vars: Vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

export function setLanguage(next: string, root = document) {
  lang = STRINGS[next] ? next : 'en';
  root.documentElement.lang = lang;
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n ?? ''); });
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml ?? ''); });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle ?? ''); });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria ?? '')); });
}

// Keep the choice in the address bar so a reload or shared link keeps it; nothing is stored.
export function rememberLanguageInUrl() {
  try {
    const url = new URL(location.href);
    if (url.searchParams.get('lang') === lang) return;
    url.searchParams.set('lang', lang);
    history.replaceState(null, '', url);
  } catch {
    // some file:// contexts refuse history changes
  }
}
